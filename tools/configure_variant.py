#!/usr/bin/env python3
"""Partition upstream mapper instances without dropping any supported mapper."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
VARIANTS = ["standard", "discrete", "special", "expansion", "vrc7", "fds"]
STANDARD = {"MMC1", "Mapper28", "MMC3", "MMC2", "MMC4", "Mapper30", "Mapper34", "Mapper66", "NesEvent"}
SPECIAL = {"Rambo1", "KS202", "VRC1", "VRC3", "VRC24", "Mapper162", "Nanjing", "Mapper164", "Mapper156", "Sachen8259", "SachenJV001", "SachenNROM", "JYCompany", "Mapper91"}
EXPANSION = {"MMC5", "N163", "VRC5", "VRC6", "Mapper69"}


def instances(source):
    aliases = {m[0]: m[1] for m in re.findall(r"wire\s+(\w+_en)\s*=\s*(.*?);", source, re.S)}
    for m in re.finditer(r"^(\w+)\s+(\w+)\s*\(", source, re.M):
        end = source.find("\n);", m.end()) + 3
        block = source[m.start():end]
        en = re.search(r"\.enable\s*\(", block)
        if not en:
            continue
        pos, level = en.end(), 1
        while level:
            level += (block[pos] == "(") - (block[pos] == ")")
            pos += 1
        expr = block[en.end():pos - 1]
        for name, value in aliases.items():
            expr = re.sub(r"\b" + name + r"\b", "(" + value + ")", expr)
        ids = sorted({int(n) for n in re.findall(r"me\[(\d+)\]", expr)})
        yield m.start(), end, m[1], m[2], block, ids


def inventory(source):
    mapping = {}
    for _, _, kind, name, _, ids in instances(source):
        if name.startswith("snd_") or not ids:
            continue
        group = ("standard" if kind in STANDARD else "special" if kind in SPECIAL else
                 "expansion" if kind in EXPANSION else "vrc7" if kind == "VRC7" else
                 "fds" if kind == "MapperFDS" else "discrete")
        for n in ids:
            assert n not in mapping, f"Mapper {n} assigned twice"
            mapping[n] = group
    return mapping


def configure(variant):
    original = (ROOT / "rtl/upstream/cart_full.sv").read_text()
    mapping = inventory(original)
    selected = {n for n, group in mapping.items() if group == variant}
    result, cursor = [], 0
    for start, end, kind, name, block, ids in instances(original):
        result.append(original[cursor:start])
        cursor = end
        if not ids:
            result.append(block)
            continue
        condition = " | ".join(f"POCKET_MAPPER_MASK[{n}]" for n in ids)
        ties = []
        for port in ("SaveStateBus_Dout", "Savestate_MAPRAMReadData", "audio_out", "data_out", "exp_audioe", "diskside_b", "prg_aoute"):
            for signal in re.findall(r"\." + port + r"\s*\(\s*([\w\[\]]+)\s*\)", block):
                ties.append(f"assign {signal} = '0;")
        if name == "map16":
            ties += [f"assign {s} = '0;" for s in ["map16_mapper_addr", "map16_data_out", "map16_prg_write", "map16_ovr"]]
        result.append(f"generate if ({condition}) begin : include_{name}\n{block}\nend else begin : omit_{name}\n" + "\n".join(ties) + "\nend endgenerate")
    result.append(original[cursor:])
    (ROOT / "rtl/upstream/cart.sv").write_text("".join(result))
    mask = sum(1 << n for n in selected)
    (ROOT / "rtl/upstream/mapper_config.vh").write_text(f"// Generated by tools/configure_variant.py: {variant}\nlocalparam [1023:0] POCKET_MAPPER_MASK = 1024'h{mask:0256x};\n")
    qsf = ROOT / "projects/nes_pocket.qsf"
    text = qsf.read_text().split("# POCKET_VARIANT_CONFIG")[0].rstrip()
    text += "\n\n# POCKET_VARIANT_CONFIG\n"
    if variant == "fds":
        text += 'set_global_assignment -name VERILOG_MACRO "POCKET_FDS=1"\n'
    qsf.write_text(text)
    manifest = {"variants": [{"id": i, "name": name, "filename": name + ".rev", "mappers": sorted(n for n, g in mapping.items() if g == name)} for i, name in enumerate(VARIANTS)],
                "upstream": "MiSTer-devel/NES_MiSTer@49a0a66", "mapper_count": len(mapping)}
    (ROOT / "mapper_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    generated = ROOT / "generated" / variant
    generated.mkdir(parents=True, exist_ok=True)
    for name, path in [("cart.sv", ROOT / "rtl/upstream/cart.sv"),
                       ("mapper_config.vh", ROOT / "rtl/upstream/mapper_config.vh"),
                       ("nes_pocket.qsf", qsf)]:
        (generated / name).write_bytes(path.read_bytes())
    print(f"Configured {variant}: {len(selected)} mappers; total {len(mapping)} across {len(VARIANTS)} images")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("variant", choices=VARIANTS + ["all"])
    selected = parser.parse_args().variant
    for variant in VARIANTS if selected == "all" else [selected]:
        configure(variant)
